// Generates src/styles/tokens.css from the design system's tokens.json.
// The design-system artifact generates this file on its page; the repo copy has to be generated here.
//   node tools/build-tokens.mjs           write the file
//   node tools/build-tokens.mjs --check   exit 1 if the file is out of date (used in CI)
import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const source = resolve(root, 'design/ui/design-system/tokens.json');
const target = resolve(root, 'src/styles/tokens.css');

const tokens = JSON.parse(readFileSync(source, 'utf8'));
const lines = [];
const add = (name, value) => lines.push(`  --${name}: ${value};`);

// Colour: one theme (dark). A value of "{other}" is an alias of another colour token.
const theme = tokens.color.themes[0].id;
for (const t of tokens.color.tokens) {
  const raw = typeof t.value === 'string' ? t.value : t.value[theme];
  const alias = /^\{([^}]+)\}$/.exec(raw);
  add(t.name, alias ? `var(--${alias[1]})` : raw);
}

// Font families become --font-display, --font-sans, --font-condensed.
for (const [name, stack] of Object.entries(tokens.type.families)) add(`font-${name}`, stack);

for (const family of ['spacing', 'radius', 'shadow', 'size', 'breakpoint']) {
  for (const t of tokens[family]?.tokens ?? []) add(t.name, t.value);
}

const css = `/* Generated by tools/build-tokens.mjs from design/ui/design-system/tokens.json. Do not edit by hand. */
:root {
  color-scheme: dark;
${lines.join('\n')}
}
`;

if (process.argv.includes('--check')) {
  const current = existsSync(target) ? readFileSync(target, 'utf8').replace(/\r\n/g, '\n') : '';
  if (current !== css) {
    console.error('src/styles/tokens.css is out of date. Run: npm run tokens');
    process.exit(1);
  }
  console.log('tokens.css is up to date');
} else {
  writeFileSync(target, css);
  console.log(`Wrote ${target} (${lines.length} custom properties)`);
}
